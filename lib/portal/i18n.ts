const DICIONARIOS: Record<Idioma, Record<Chave, string>> = { pt, en };

/** Texto no idioma, trocando {variavel} pelos valores. */
export function traduzir(idioma: Idioma, chave: Chave, vars: Record<string, string | number> = {}): string {
  const base = DICIONARIOS[idioma][chave] ?? pt[chave];
  return base.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

/** Atalho: const t = tradutor(idioma); t("nav.sair"). */
export function tradutor(idioma: Idioma) {
  return (chave: Chave, vars?: Record<string, string | number>) => traduzir(idioma, chave, vars);
}

export function ehIdioma(v: unknown): v is Idioma {
  return v === "pt" || v === "en";
}

